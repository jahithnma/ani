  var LANG_KEY = "cd_lang";
  var lang = "ta";
  try { lang = localStorage.getItem(LANG_KEY) || "ta"; } catch (e) { /* storage unavailable */ }
  if (!STRINGS[lang]) lang = "ta";

  function T(key, vars) {
    var s = STRINGS[lang][key] || STRINGS.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) { s = s.split("{" + k + "}").join(vars[k]); });
    }
    return s;
  }

  // Fill every element marked data-t (text) / data-tp (placeholder)
  function applyAll() {
    document.documentElement.lang = lang;
    Array.prototype.forEach.call(document.querySelectorAll("[data-t]"), function (el) {
      el.textContent = T(el.getAttribute("data-t"));
    });
    Array.prototype.forEach.call(document.querySelectorAll("[data-tp]"), function (el) {
      el.placeholder = T(el.getAttribute("data-tp"));
    });
    Array.prototype.forEach.call(document.querySelectorAll(".lang button"), function (b) {
      b.classList.toggle("on", b.getAttribute("data-lang") === lang);
    });
  }

  var listeners = [];

  function setLang(l) {
    if (!STRINGS[l]) return;
    lang = l;
    try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* storage unavailable */ }
    applyAll();
    listeners.forEach(function (fn) { fn(l); });
  }

  document.addEventListener("click", function (e) {
    var b = e.target.closest && e.target.closest(".lang button");
    if (b) setLang(b.getAttribute("data-lang"));
  });

  window.T = T;
  window.I18N = {
    apply: applyAll,
    set: setLang,
    get: function () { return lang; },
    onChange: function (fn) { listeners.push(fn); }
  };
